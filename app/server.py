"""
app/server.py

FastAPI local server for CODEscribe.
Exposes REST endpoints for model health, curated examples, and documentation generation.

Endpoints:
- POST /api/document: Preprocesses Python code, generates CodeT5 documentation and Mermaid flowchart.
- GET  /api/health: Reports API status, model loading state, device, and GPU VRAM.
- GET  /api/examples: Returns curated Python code examples for testing.

Security & Safety:
- Binds strictly to 127.0.0.1 by default.
- Never executes user-submitted code.
- Restricts payload sizes to avoid memory exhaustion.
- Never logs entire submitted source code payloads.
"""

from __future__ import annotations

from contextlib import asynccontextmanager
import logging
from pathlib import Path
import platform
import sys
from typing import Any, Dict, List, Optional

from fastapi import FastAPI, HTTPException, Request, status
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field
import torch
import uvicorn

# Ensure workspace root is in sys.path
_workspace_root = Path(__file__).resolve().parent.parent
if str(_workspace_root) not in sys.path:
    sys.path.insert(0, str(_workspace_root))

from app.generator import (
    CodeScribeGenerator,
    CodeSyntaxError,
    ModelNotLoadedError,
)

logging.basicConfig(
    level=logging.INFO,
    format="[%(asctime)s] [%(levelname)s] [%(name)s] %(message)s",
    datefmt="%Y-%m-%d %H:%M:%S",
)
logger = logging.getLogger("CODEscribe.Server")

# Maximum permitted characters in a single submitted source code payload (100 KB)
MAX_SOURCE_CODE_CHARS = 100_000

# Global generator instance
_global_generator: Optional[CodeScribeGenerator] = None


def get_generator() -> CodeScribeGenerator:
    """Retrieve the shared generator instance."""
    global _global_generator
    if _global_generator is None:
        _global_generator = CodeScribeGenerator()
    return _global_generator


def set_generator(generator: CodeScribeGenerator) -> None:
    """Explicitly set or mock the generator instance (used for testing)."""
    global _global_generator
    _global_generator = generator


@asynccontextmanager
async def lifespan(app: FastAPI):
    """Application lifecycle: loads model at startup, unloads at shutdown."""
    gen = get_generator()
    try:
        logger.info("Initializing CODEscribe generator at server startup...")
        gen.load()
    except Exception as exc:
        logger.warning(
            "Could not load local model at startup (server will operate in degraded mode): %s",
            exc,
        )

    yield

    logger.info("Shutting down CODEscribe server and unloading resources...")
    gen.unload()


# Initialize FastAPI app
app = FastAPI(
    title="CODEscribe Local Inference API",
    description="Privacy-first local API for Python API documentation and Mermaid flowchart synthesis.",
    version="1.0.0",
    lifespan=lifespan,
)

# CORS configuration for local UI integration
app.add_middleware(
    CORSMiddleware,
    allow_origins=[
        "http://localhost:5173",
        "http://127.0.0.1:5173",
        "http://localhost:3000",
        "http://127.0.0.1:3000",
        "http://127.0.0.1:8000",
        "http://localhost:8000",
    ],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


# ---------------------------------------------------------------------------
# Request & Response Schemas
# ---------------------------------------------------------------------------
class DocumentRequest(BaseModel):
    code: str = Field(
        ...,
        min_length=1,
        max_length=MAX_SOURCE_CODE_CHARS,
        description="Python source code to document.",
    )
    num_beams: int = Field(
        default=1,
        ge=1,
        le=5,
        description="Beam count for generation search (default: 1 for deterministic greedy search).",
    )
    max_new_tokens: int = Field(
        default=128,
        ge=16,
        le=512,
        description="Maximum new tokens generated by CodeT5.",
    )
    temperature: float = Field(
        default=1.0,
        gt=0.0,
        le=2.0,
        description="Generation temperature.",
    )
    do_sample: bool = Field(
        default=False,
        description="Enable stochastic sampling if True; deterministic greedy search if False.",
    )
    include_mermaid: bool = Field(
        default=True,
        description="Whether to generate an AST-based Mermaid control flowchart.",
    )


class ASTMetadataResponse(BaseModel):
    function_names: List[str]
    parameters: List[str]
    return_annotation: Optional[str] = None
    docstring_stripped: bool
    syntax_valid: bool


class TimingResponse(BaseModel):
    preprocessing_ms: float
    inference_ms: float
    mermaid_ms: float
    total_ms: float


class DocumentResponse(BaseModel):
    success: bool
    markdown: str
    docstring: str
    mermaid_code: Optional[str] = None
    ast_metadata: ASTMetadataResponse
    timing_ms: TimingResponse
    device: str
    status: str
    error_message: Optional[str] = None


class HealthResponse(BaseModel):
    status: str
    model_loaded: bool
    model_path: str
    device: str
    cuda_available: bool
    gpu_name: Optional[str] = None
    vram_allocated_mb: Optional[float] = None
    vram_total_mb: Optional[float] = None
    torch_version: str
    transformers_version: str


class ExampleSnippet(BaseModel):
    id: str
    title: str
    description: str
    code: str


class ExamplesResponse(BaseModel):
    examples: List[ExampleSnippet]


