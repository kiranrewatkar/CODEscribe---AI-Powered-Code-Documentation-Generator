@app.get("/api/health", response_model=HealthResponse)
async def health_check() -> HealthResponse:
    """Return system readiness, device configuration, and model status."""
    gen = get_generator()

    cuda_avail = torch.cuda.is_available()
    gpu_name = torch.cuda.get_device_name(0) if cuda_avail else None
    vram_alloc = None
    vram_total = None

    if cuda_avail:
        vram_alloc = round(torch.cuda.memory_allocated(0) / (1024 ** 2), 2)
        vram_total = round(torch.cuda.get_device_properties(0).total_memory / (1024 ** 2), 2)

    import transformers

    return HealthResponse(
        status="ok" if gen.is_loaded else "degraded",
        model_loaded=gen.is_loaded,
        model_path=str(gen.model_path),
        device=gen.device,
        cuda_available=cuda_avail,
        gpu_name=gpu_name,
        vram_allocated_mb=vram_alloc,
        vram_total_mb=vram_total,
        torch_version=torch.__version__,
        transformers_version=transformers.__version__,
    )


