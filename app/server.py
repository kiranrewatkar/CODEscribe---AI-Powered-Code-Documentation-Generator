@app.post("/api/document", response_model=DocumentResponse)
async def generate_document(payload: DocumentRequest) -> DocumentResponse:
    """
    Generate natural-language Markdown documentation and a Mermaid flowchart
    from Python source code.
    """
    code_str = payload.code.strip()
    if not code_str:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Source code cannot be empty or contain only whitespace.",
        )

    # Avoid logging the entire code payload
    logger.info(
        "Received document request: %d characters, num_beams=%d, max_tokens=%d",
        len(code_str),
        payload.num_beams,
        payload.max_new_tokens,
    )

    gen = get_generator()
    if not gen.is_loaded:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Model is not loaded. Ensure checkpoint exists at model/codescribe.",
        )

    try:
        result = gen.generate_documentation(
            source_code=payload.code,
            num_beams=payload.num_beams,
            max_new_tokens=payload.max_new_tokens,
            temperature=payload.temperature,
            do_sample=payload.do_sample,
            include_mermaid=payload.include_mermaid,
        )

        return DocumentResponse(
            success=result.success,
            markdown=result.markdown,
            docstring=result.docstring,
            mermaid_code=result.mermaid_code,
            ast_metadata=ASTMetadataResponse(
                function_names=result.ast_metadata.function_names,
                parameters=result.ast_metadata.parameters,
                return_annotation=result.ast_metadata.return_annotation,
                docstring_stripped=result.ast_metadata.docstring_stripped,
                syntax_valid=result.ast_metadata.syntax_valid,
            ),
            timing_ms=TimingResponse(
                preprocessing_ms=result.timing_ms.preprocessing_ms,
                inference_ms=result.timing_ms.inference_ms,
                mermaid_ms=result.timing_ms.mermaid_ms,
                total_ms=result.timing_ms.total_ms,
            ),
            device=result.device,
            status=result.status,
            error_message=result.error_message,
        )

    except CodeSyntaxError as e:
        logger.warning("Code syntax validation failed: %s", e)
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"Python syntax error: {str(e)}",
        ) from e
    except ModelNotLoadedError as e:
        logger.error("Model invocation failed: %s", e)
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Model is not loaded.",
        ) from e
    except Exception as e:
        logger.error("Internal documentation generation error: %s", e, exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="An error occurred while generating documentation.",
        ) from e


def run_server(host: str = "127.0.0.1", port: int = 8000, reload: bool = False) -> None:
    """Entry point for running the local Uvicorn server."""
    logger.info("Starting CODEscribe API server on http://%s:%d", host, port)
    uvicorn.run("app.server:app", host=host, port=port, reload=reload)


if __name__ == "__main__":
    run_server()
